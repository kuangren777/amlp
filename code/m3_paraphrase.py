"""E3a paraphrase drift (plan.md §13, RQ4a): benign runs of the 48 holdout tasks with the user prompt replaced by one
of 3 frozen paraphrases, arms none / amlp / progent, 1 run per (task, paraphrase, arm) = 48 × 3 × 3 = 432 per model
(minus dropped paraphrases). Utility = the ORIGINAL user task's AgentDojo utility function (meaning is preserved).

Paraphrases: generated ONCE by `--generate` (gpt-5.5, harness.CLIENT, temperature 0) into
data/m3/paraphrases_holdout.json with an automatic value-preservation check (`missing_values`); the runner only reads
the frozen file and refuses to regenerate it.

Prompt override: the paraphrase is passed as `harness.run_pair(..., user_prompt=...)`, i.e. through the pipeline's
InitQuery. No AgentDojo task object is mutated, so threads cannot see each other's prompt (tested).

AMLP arm (af4 review 2026-10-06): the M3 selected config at the primary eps (m3_select.load_selected) on the M3
mining pool, exclude_tasks=C.HOLDOUT. A deployed AMLP sees only the paraphrased request, so every per-request input is
computed on the PARAPHRASE: the LLM tool prediction (predictor of the selected config, the exact prompt template of
pilot/p1b_llm_envelope.py that produced envbuild.PRED, temperature 0, fail-open to all side tools on a parse failure),
the bge-m3 embedding (harness.CLIENT, model "bge-m3", as pilot/p1_loto.py produced the snapshot cache) used to pick the
r nearest mined tasks, and the prompt literals. Mined tasks, their embeddings (envbuild.E) and the value layer are
unchanged (m3_envelope.build with predictor=None, r=0 gives exactly the pool-derived part). Paraphrase predictions and
embeddings are cached in data/m3/paraphrase_pred_cache.json (smoke: data/m3_smoke_para/), never in envbuild.PRED or
pilot/snap. Rows carry pred_source="paraphrase", emb_source="paraphrase".
Progent arm: the policy is generated by gpt-4o from the PARAPHRASED prompt on every run (prompt-driven), without the
baselines/cache policy cache (use_cache=False, so the shared cache keyed by the original prompt is neither read nor
overwritten). port_commit is recorded.
usage: python3 m3_paraphrase.py --generate
       python3 m3_paraphrase.py --model M --workers N [--dry-run] [--smoke] [--limit N]"""
